/**
 * Sitewide experiment runner.
 *
 * Install (current): <script src="https://YOUR-SITEWIDE-DOMAIN/api/snippet/js/YOUR_SITE_ID"></script>
 *   Synchronous, FIRST thing in <head>. That route serves this file with the
 *   site's config baked in (edge-cached), so the anti-flicker CSS and the
 *   variant payloads exist before the browser paints anything. A deferred
 *   script runs after first paint is already possible — the original content
 *   shows, then blinks to the variant. Sync-in-head is how every vendor in
 *   this category avoids that; the cost is a few ms of parse blocking on a
 *   small cached file.
 *
 * Install (legacy, still supported):
 *   <script defer src="https://YOUR-SITEWIDE-DOMAIN/snippet.js" data-site-id="YOUR_SITE_ID"></script>
 *
 * Debug mode: add ?sw_debug=1 to any URL on the site (or run
 * `localStorage.sw_debug = "1"` in the console) and the snippet logs every
 * step — visitor id, config source (cache vs network), bucketing decisions,
 * element applies, events, and why/when the page was released from hiding.
 *
 * Preview links: ?sw_preview=<token> (generated by the experiment builder)
 * applies ONE variant's change and nothing else — no cookie, no config
 * fetch, no bucketing, no events. Lets founders see a variant on the live
 * site before the experiment is even created, let alone activated.
 *
 * What it does on every page load:
 *   1. Reads/creates a first-party visitor id cookie (sw_vid).
 *   2. Loads the site's experiment config — embedded in this very file on the
 *      sync install (available before paint, changes land in ~30s). Legacy
 *      installs fall back to localStorage cache, then the network; that cache
 *      refreshes in the background, so config changes take effect one page
 *      load later.
 *   3. Assigns the visitor to a variant DETERMINISTICALLY — hash(visitorId +
 *      experimentId) mapped onto variant weights. Same visitor, same variant,
 *      every page, every visit, no stored assignments.
 *   4. Applies the variant's change and re-applies via MutationObserver —
 *      client-rendered React/Next sites build the DOM late and rewrite it on
 *      hydration, so one-shot patching is not enough. The observer starts on
 *      documentElement immediately (works while HTML is still streaming in)
 *      and disconnects a grace period after everything is applied.
 *   5. Reports exposure + conversion events as text/plain beacons (CORS
 *      "simple requests" — no preflight). The server dedupes per visitor.
 *
 * Anti-flicker strategy (the important part):
 *   - Target elements stay hidden (visibility:hidden — layout preserved)
 *     until their change is ACTUALLY applied. On client-rendered apps the
 *     element may not exist for hundreds of ms; hiding is by CSS rule, so it
 *     covers the element from the instant the framework creates it — the
 *     visitor never sees the original text flash before the swap. On the sync
 *     install this rule exists before first paint, so nothing ever flashes.
 *   - Whole-page hide exists ONLY on the legacy path, on a visitor's
 *     first-ever load (no cache, config must be fetched), and only until the
 *     config arrives — then it downgrades to the element-scoped hide above.
 *   - Failsafes: the whole-page hide is capped at 400ms (a slow fetch can
 *     never blank the page); element-scoped hides are capped at 2500ms
 *     (they're invisible-by-design — layout is kept, only tested elements are
 *     covered — so a longer leash for slow mobile hydration costs nothing).
 */
(function () {
  "use strict";

  var script = document.currentScript;
  if (!script) return;
  // Sync install: /api/snippet/js/[siteId] prepends `var __SW_EMBED__ =
  // {siteId, config}` to this file — site id and config with zero extra
  // requests. The typeof guard keeps the static /snippet.js file working.
  var EMBED = typeof __SW_EMBED__ !== "undefined" ? __SW_EMBED__ : null;
  var SITE_ID = (EMBED && EMBED.siteId) || script.getAttribute("data-site-id");
  if (!SITE_ID) return;
  var API = new URL(script.src).origin;
  var CACHE_KEY = "sw_cfg_" + SITE_ID;

  // ── Debug logging (?sw_debug=1 or localStorage.sw_debug="1") ─────────────
  var DEBUG = false;
  try {
    DEBUG = /[?&]sw_debug=1/.test(location.search) || localStorage.getItem("sw_debug") === "1";
  } catch (e) {
    /* storage blocked — debug stays off */
  }
  function dbg() {
    if (!DEBUG) return;
    var args = ["[sitewide]"];
    for (var i = 0; i < arguments.length; i++) args.push(arguments[i]);
    console.log.apply(console, args);
  }

  // ── Hiding / releasing (anti-flicker) ─────────────────────────────────────
  // One <style> element whose contents we can swap: starts as a whole-page
  // hide on first visit, downgrades to element-only hiding once we know the
  // selectors, and is removed entirely on release.
  var hideEl = null;
  var released = false;
  var hideMode = null; // "page" (legacy first visit only) | "elements"
  function setHide(cssText, mode) {
    if (released) return;
    hideMode = mode;
    if (!hideEl) {
      hideEl = document.createElement("style");
      document.documentElement.appendChild(hideEl);
    }
    hideEl.textContent = cssText;
  }
  function release(reason) {
    if (released) return;
    released = true;
    if (hideEl && hideEl.parentNode) hideEl.parentNode.removeChild(hideEl);
    hideEl = null;
    dbg("released page (" + reason + ")");
  }
  // Two-tier failsafe. A whole-page hide (legacy path, first visit, config
  // still in flight) may never exceed 400ms — a slow fetch can't blank the
  // page. Element-scoped hides keep layout and cover only tested elements,
  // so they get a longer leash for slow mobile hydration.
  setTimeout(function () {
    if (hideMode === "page") release("400ms first-visit failsafe");
  }, 400);
  setTimeout(function () {
    release("2500ms failsafe");
  }, 2500);

  // ── Preview links (?sw_preview=<token>) ───────────────────────────────────
  // The token is base64url({ s: selector, f: fallback, p: payload }), built
  // by the experiment builder. It carries the change ITSELF, so it works
  // before the experiment exists in the database. Preview visits apply only
  // this one change: no visitor cookie, no config fetch, no bucketing, no
  // events — a preview leaves zero traces in the data.
  // (findElement/applyPayload are function declarations — hoisted, so calling
  // them from up here is safe.)
  var previewParam = location.search.match(/[?&]sw_preview=([^&]+)/);
  if (previewParam) {
    var preview = null;
    try {
      var token = decodeURIComponent(previewParam[1]).replace(/-/g, "+").replace(/_/g, "/");
      while (token.length % 4) token += "=";
      // atob → escape → decodeURIComponent reads the base64 bytes as UTF-8
      preview = JSON.parse(decodeURIComponent(escape(atob(token))));
    } catch (e) {
      dbg("malformed sw_preview token — falling back to a normal run");
    }
    if (preview && preview.p) {
      dbg("PREVIEW MODE (link): applying", preview.p, "to", preview.s);
      // Same anti-flicker as a real run: hide the target until the change
      // lands (the element-scoped failsafe above still caps the wait).
      if (preview.s) setHide(preview.s + "{visibility:hidden !important}", "elements");
      var previewApplied = false;
      observeAndApply(function () {
        var el = findElement(preview.s, preview.f);
        if (!el) return false;
        applyPayload(el, preview.p);
        if (!previewApplied) {
          previewApplied = true;
          release("preview applied");
        }
        return true;
      });
      return; // never falls through to bucketing or tracking
    }
  }

  // ── Visitor identity ──────────────────────────────────────────────────────
  function getVisitorId() {
    var m = document.cookie.match(/(?:^|;\s*)sw_vid=([^;]+)/);
    if (m) return m[1];
    var vid =
      Date.now().toString(36) +
      "-" +
      Math.random().toString(36).slice(2, 10) +
      Math.random().toString(36).slice(2, 10);
    document.cookie = "sw_vid=" + vid + ";path=/;max-age=31536000;SameSite=Lax";
    return vid;
  }
  var VISITOR_ID = getVisitorId();
  dbg("visitor:", VISITOR_ID);

  // ── Preview override (?sw_bucket=N) ───────────────────────────────────────
  // Forces the bucket number for ALL experiments on this page load, so you can
  // see any arm on demand: ?sw_bucket=99 → last variant, ?sw_bucket=0 →
  // control. Preview visits record NO events — forced traffic isn't data.
  var FORCED_BUCKET = null;
  var forced = location.search.match(/[?&]sw_bucket=(\d+)/);
  if (forced) {
    FORCED_BUCKET = Math.min(99, parseInt(forced[1], 10));
    dbg("PREVIEW MODE: bucket forced to", FORCED_BUCKET, "— events suppressed");
  }

  // ── Deterministic bucketing ───────────────────────────────────────────────
  // FNV-1a hash → 0-99. Keyed per experiment so assignments are independent.
  function bucket(experimentId) {
    if (FORCED_BUCKET !== null) return FORCED_BUCKET;
    var str = VISITOR_ID + ":" + experimentId;
    var h = 0x811c9dc5;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = (h * 0x01000193) >>> 0;
    }
    return h % 100;
  }

  // Walk cumulative weights in variant order; the bucket lands in one slot.
  function pickVariant(experiment) {
    var b = bucket(experiment.id);
    var cum = 0;
    for (var i = 0; i < experiment.variants.length; i++) {
      cum += experiment.variants[i].weight;
      if (b < cum) return experiment.variants[i];
    }
    return experiment.variants[0]; // weights didn't sum to 100 — fall back to control
  }

  // ── Element finding ───────────────────────────────────────────────────────
  // Try the stored selector, then the {tag, text} fallback (survives redeploys
  // that restructure the page but keep the copy).
  function findElement(selector, fallback) {
    if (selector) {
      try {
        var el = document.querySelector(selector);
        if (el) return el;
      } catch (e) {
        /* invalid selector — fall through to fallback */
      }
    }
    if (fallback && fallback.tag && fallback.text) {
      var candidates = document.getElementsByTagName(fallback.tag);
      for (var i = 0; i < candidates.length; i++) {
        var text = (candidates[i].innerText || "").trim();
        if (text && text.indexOf(fallback.text.slice(0, 40)) === 0) {
          return candidates[i];
        }
      }
    }
    return null;
  }

  // ── Applying changes (idempotent — safe to call on every mutation) ────────
  // Rich-text swap: one payload string per non-whitespace text node of the
  // element, in document order. Rewriting text NODES (not textContent) keeps
  // inner spans — and their gradient/color styling — intact. Each node's own
  // leading/trailing whitespace is preserved so words don't jam together.
  // If the markup changed since capture (node count mismatch after a
  // redeploy), fall back to a flat replace — join with spaces, which HTML
  // rendering collapses safely.
  function applyTextParts(el, parts) {
    var nodes = [];
    var walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = walker.nextNode())) {
      if (n.nodeValue && n.nodeValue.replace(/\s+/g, "")) nodes.push(n);
    }
    if (nodes.length !== parts.length) {
      var flat = parts.join(" ");
      if (el.textContent !== flat) el.textContent = flat;
      return;
    }
    for (var i = 0; i < nodes.length; i++) {
      var cur = nodes[i].nodeValue;
      var next = cur.match(/^\s*/)[0] + parts[i] + cur.match(/\s*$/)[0];
      if (cur !== next) nodes[i].nodeValue = next;
    }
  }

  function applyPayload(el, payload) {
    if (!payload) return;
    if (payload.textParts !== undefined) {
      applyTextParts(el, payload.textParts);
    } else if (payload.text !== undefined && el.textContent !== payload.text) {
      el.textContent = payload.text;
    }
    if (payload.src !== undefined && el.getAttribute("src") !== payload.src) {
      el.setAttribute("src", payload.src);
      el.removeAttribute("srcset"); // srcset would override our src
    }
    if (payload.hide) {
      if (el.style.getPropertyValue("display") !== "none") {
        el.style.setProperty("display", "none", "important");
      }
    }
    if (payload.styles) {
      var map = {
        color: "color",
        backgroundColor: "background-color",
        fontSize: "font-size",
      };
      for (var key in payload.styles) {
        var css = map[key];
        if (css && el.style.getPropertyValue(css) !== payload.styles[key]) {
          el.style.setProperty(css, payload.styles[key], "important");
        }
      }
    }
  }

  // ── Apply loop ────────────────────────────────────────────────────────────
  // Runs applyFn now, then re-runs it on every DOM mutation until it reports
  // done (returns true) — and for a grace period after that, because React
  // hydration can rewrite already-patched elements seconds later. Observing
  // documentElement (not body) means this works while the HTML is still
  // streaming in: the sync install runs before <body> even exists, and the
  // parser's own node insertions fire the observer, so changes apply the
  // moment their target is parsed — usually before it's ever painted.
  // The observer always disconnects (grace after done, hard stop otherwise):
  // no permanent per-mutation querySelector work on chatty apps.
  function observeAndApply(applyFn) {
    var GRACE_MS = 10000; // survives hydration rewrites after everything applied
    var HARD_STOP_MS = 30000; // absolute cap even if a target never appears
    var graceTimer = null;
    var observer = new MutationObserver(check);
    function stop(why) {
      observer.disconnect();
      dbg("apply loop stopped (" + why + ")");
    }
    function check() {
      if (!applyFn() || graceTimer) return;
      graceTimer = setTimeout(function () {
        stop("done + grace period over");
      }, GRACE_MS);
    }
    check();
    observer.observe(document.documentElement, {
      childList: true,
      subtree: true,
      characterData: true,
    });
    setTimeout(function () {
      if (!graceTimer) stop("hard stop — some targets never appeared");
    }, HARD_STOP_MS);
  }

  // ── Event reporting ───────────────────────────────────────────────────────
  // Body is a PLAIN STRING → the request is a CORS "simple request" (no
  // preflight), which sendBeacon can always deliver, even cross-origin.
  // The server parses the body as JSON regardless of content type and dedupes
  // per visitor — fire-and-forget.
  function sendEvent(experimentId, variantId, eventType) {
    if (FORCED_BUCKET !== null) {
      dbg("event suppressed (preview mode):", eventType);
      return;
    }
    var body = JSON.stringify({
      experiment_id: experimentId,
      variant_id: variantId,
      visitor_id: VISITOR_ID,
      event_type: eventType,
      page_url: location.href,
    });
    var url = API + "/api/snippet/event";
    var sent = false;
    if (navigator.sendBeacon) {
      try {
        sent = navigator.sendBeacon(url, body);
      } catch (e) {
        sent = false;
      }
    }
    if (!sent) {
      fetch(url, { method: "POST", body: body, keepalive: true }).catch(function () {});
    }
    dbg("event sent:", eventType, "(experiment " + experimentId.slice(0, 8) + "…)");
  }

  // ── Path matching (exact path, trailing-slash tolerant) ──────────────────
  function pathMatches(path) {
    if (!path) return false;
    var norm = function (p) {
      return p.length > 1 ? p.replace(/\/+$/, "") : p;
    };
    return norm(location.pathname) === norm(path);
  }

  // ── Config cache ──────────────────────────────────────────────────────────
  function readCache() {
    try {
      var raw = localStorage.getItem(CACHE_KEY);
      return raw ? JSON.parse(raw) : null;
    } catch (e) {
      return null;
    }
  }
  function writeCache(config) {
    try {
      localStorage.setItem(CACHE_KEY, JSON.stringify(config));
    } catch (e) {
      /* storage full/blocked — cache is an optimization, not a requirement */
    }
  }
  function fetchConfig() {
    return fetch(API + "/api/snippet/config?site_id=" + encodeURIComponent(SITE_ID)).then(
      function (res) {
        return res.json();
      }
    );
  }

  // CSS that hides exactly the elements the given pending changes target.
  function hideCssFor(pending) {
    var selectors = [];
    pending.forEach(function (item) {
      if (item.exp.selector) selectors.push(item.exp.selector);
    });
    return selectors.length ? selectors.join(",") + "{visibility:hidden !important}" : "";
  }

  // ── Core: act on a config (apply changes, wire goals, fire events) ───────
  function run(config) {
    var experiments = (config && config.experiments) || [];
    var pending = []; // { exp, payload, applied } — applied flips on first success

    experiments.forEach(function (exp) {
      // Completed experiment with a winner: serve the winner to everyone,
      // no tracking. This IS "promoting the winner to 100%".
      if (exp.status === "completed") {
        if (exp.winner_variant_id && pathMatches(exp.page_path)) {
          var winner = null;
          for (var i = 0; i < exp.variants.length; i++) {
            if (exp.variants[i].id === exp.winner_variant_id) winner = exp.variants[i];
          }
          if (winner && winner.payload) {
            pending.push({ exp: exp, variant: winner, payload: winner.payload, applied: false });
            dbg("serving promoted winner for", exp.id.slice(0, 8) + "…");
          }
        }
        return;
      }

      if (exp.status !== "running") return;
      var variant = pickVariant(exp);
      // Killed by the agent's circuit breaker (significantly losing): the
      // variant keeps its bucket range — reweighting would silently reshuffle
      // visitors across every other arm — but its visitors get the control
      // experience (no change applied) and stop being tracked entirely.
      if (variant.killed) {
        dbg("experiment", exp.id.slice(0, 8) + "…", "variant killed — serving original, no tracking");
        return;
      }
      dbg(
        "experiment",
        exp.id.slice(0, 8) + "…",
        "bucket=" + bucket(exp.id),
        "→",
        variant.is_control ? "CONTROL" : "VARIANT",
        "(" + variant.id.slice(0, 8) + "…)"
      );

      // On the experiment page: apply the change, count the exposure.
      // (If this config came from a stale cache and the experiment was
      // paused meanwhile, the server rejects the events — data stays clean.)
      if (pathMatches(exp.page_path)) {
        if (variant.payload) {
          pending.push({ exp: exp, variant: variant, payload: variant.payload, applied: false });
        }
        sendEvent(exp.id, variant.id, "exposure");

        // Click goal: capture-phase listener, works on late-rendered elements.
        if (exp.goal_type === "click" && exp.goal_selector) {
          document.addEventListener(
            "click",
            function (e) {
              try {
                if (e.target && e.target.closest && e.target.closest(exp.goal_selector)) {
                  sendEvent(exp.id, variant.id, "conversion");
                }
              } catch (err) {
                /* bad selector — ignore */
              }
            },
            true
          );
        }
      }

      // Pageview goal: the conversion page is usually NOT the experiment
      // page. Deterministic bucketing recomputes the same variant here with
      // no stored state. The server only counts it if this visitor also has
      // an exposure row.
      if (exp.goal_type === "pageview" && pathMatches(exp.goal_page_path)) {
        sendEvent(exp.id, variant.id, "conversion");
      }
    });

    if (pending.length === 0) {
      release("no changes on this page");
      return;
    }

    // From here on, hide ONLY the elements we're about to change. On
    // client-rendered apps (React/Vite) these elements may not exist yet —
    // a CSS rule covers them from the instant the framework creates them.
    setHide(hideCssFor(pending), "elements");

    // Selector-miss reporting: a change still unapplied 8s in means the
    // target element is probably gone (a redeploy restructured the page) and
    // this visitor is seeing the original while counted as a variant
    // exposure. Report it so the agent can pause the experiment instead of
    // letting it collect garbage. 8s is far beyond slow-device hydration but
    // before the 30s hard stop; the server dedupes per visitor, and the agent
    // requires several distinct visitors before pausing anything.
    setTimeout(function () {
      pending.forEach(function (item) {
        if (!item.applied && item.exp.status === "running") {
          dbg("selector miss:", item.exp.selector);
          sendEvent(item.exp.id, item.variant.id, "selector_miss");
        }
      });
    }, 8000);

    // Returns true when every pending change has been applied at least once.
    function applyAll() {
      var allApplied = true;
      pending.forEach(function (item) {
        var el = findElement(item.exp.selector, item.exp.selector_fallback);
        if (el) {
          applyPayload(el, item.payload);
          if (!item.applied) {
            item.applied = true;
            dbg("applied change to", item.exp.selector);
          }
        }
        if (!item.applied) allApplied = false;
      });
      return allApplied;
    }

    // Apply as elements appear (even mid-parse); only release the hide once
    // everything is actually applied (or a failsafe fires) — releasing
    // earlier would flash the original content.
    observeAndApply(function () {
      var done = applyAll();
      if (done && !released) release("all changes applied");
      return done;
    });
  }

  // ── Main ─────────────────────────────────────────────────────────────────
  if (EMBED && EMBED.config) {
    // Sync install: config shipped inside this file, available before first
    // paint. Element-scoped hiding only — the whole-page hide never runs on
    // this path, and there is no config request at all. The cache write keeps
    // the legacy path warm in case the install method ever changes.
    dbg("config source: embedded in script (sync install)");
    writeCache(EMBED.config);
    run(EMBED.config);
  } else {
    var cached = readCache();

    if (cached) {
      dbg("config source: localStorage cache (refreshing in background)");
      run(cached);
      fetchConfig()
        .then(function (config) {
          writeCache(config);
          dbg("background config refresh done — takes effect next page load");
        })
        .catch(function () {});
    } else {
      dbg("config source: network (first visit on this device)");
      // Nothing to go on yet — hide the page until config arrives (400ms cap).
      // run() immediately downgrades this to element-only hiding.
      setHide("html{opacity:0 !important}", "page");
      fetchConfig()
        .then(function (config) {
          writeCache(config);
          run(config);
        })
        .catch(function (err) {
          dbg("config fetch/run failed:", err && err.message ? err.message : err);
          release("config fetch failed");
        });
    }
  }
})();
